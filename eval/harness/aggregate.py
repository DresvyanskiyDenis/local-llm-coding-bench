# --------------------------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------------------------
def _mean3(xs: list[float]) -> float | None:
    xs = [x for x in xs if isinstance(x, (int, float)) and not isinstance(x, bool)]
    return round(st.mean(xs), 3) if xs else None


def _median1(xs: list[float]) -> float | None:
    xs = [x for x in xs if isinstance(x, (int, float)) and not isinstance(x, bool)]
    return round(st.median(xs), 1) if xs else None


def task_set(which: str) -> frozenset[str]:
    if which == "1":
        return ROUND1_TASKS
    if which == "2":
        return ROUND2_TASKS
    return ROUND1_TASKS | ROUND2_TASKS


def load_units(results: Path, tasks: frozenset[str]) -> list[dict]:
    """Every unit result JSON whose task is in `tasks`. Malformed files are reported, not fatal."""
    units, bad = [], []
    for p in sorted(results.glob("*__*__*__*__rep*.json")):
        if not UNIT_RE.match(p.name):
            continue
        try:
            d = json.loads(p.read_text())
        except (json.JSONDecodeError, UnicodeDecodeError) as e:
            bad.append((p.name, str(e)))
            continue
        if d.get("task") in tasks:
            units.append(d)
    if bad:
        for name, err in bad:
            print(f"warn: unparseable unit {name}: {err}", file=sys.stderr)
    return units


def load_judged(results: Path, tasks: frozenset[str]) -> tuple[dict, dict]:
    """(per-model pooled D scores, per-config D scores) from DTEXT_JUDGED.json."""
    by_model: dict[str, list[float]] = defaultdict(list)
    by_config: dict[tuple[str, str], list[float]] = defaultdict(list)
    p = results / "DTEXT_JUDGED.json"
    if not p.exists():
        return by_model, by_config
    for r in json.loads(p.read_text()):
        if r.get("task") not in tasks:
            continue
        s = r.get("score")
        if not isinstance(s, (int, float)) or isinstance(s, bool):
            continue
        by_model[r["model"]].append(s)
        by_config[(r["model"], r["quant"])].append(s)
    return by_model, by_config


def probe_decode(results: Path, model: str, quant: str) -> float | None:
    p = results / f"probe__{model}__{quant}.json"
    if not p.exists():
        return None
    d = json.loads(p.read_text())
    dec = [
        s["decode_tps"]
        for pt in d.get("points", [])
        for s in (pt.get("cold_samples") or []) + (pt.get("warm_samples") or [])
        if s.get("decode_tps")
    ]
    return _median1(dec)


def load_external(
    results: Path, pattern: str, key: str
) -> dict[tuple[str, str], float | None]:
    """bcb__* / ifeval__* result files. Absent is normal -- returns {} rather than crashing."""
    out: dict[tuple[str, str], float | None] = {}
    for p in sorted(results.glob(pattern)):
        try:
            d = json.loads(p.read_text())
        except (json.JSONDecodeError, UnicodeDecodeError) as e:
            print(f"warn: unparseable external file {p.name}: {e}", file=sys.stderr)
            continue
        model, quant = d.get("model"), d.get("quant")
        if model is None or quant is None:
            print(f"warn: {p.name} has no model/quant, skipped", file=sys.stderr)
            continue
        v = d.get(key)
        out[(model, quant)] = (
            v if isinstance(v, (int, float)) and not isinstance(v, bool) else None
        )
    return out


