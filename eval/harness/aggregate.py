"""aggregate.py — reproduce the leaderboard composite from the on-disk result units.

`docs/leaderboard.md` and `eval/results/LEADERBOARD.md` were WRITTEN BY AN AGENT SESSION, not
generated by code. For a round whose thesis is "graders nobody here wrote", the ranking itself
must be reproducible from the result files. This script is that reproduction.

    uv run eval/harness/aggregate.py --round 1
    uv run eval/harness/aggregate.py --round all --out eval/results/AGGREGATE__roundall.md

--out is taken literally; --round all into AGGREGATE.md overwrites the published round-1 table.

Design property #1 — ROUND1_TASKS / ROUND2_TASKS are explicit, hard-coded sets. `--round 1`
scores ONLY the round-1 task ids, so the round-1 composite stays byte-for-byte reproducible as
round-2 task directories land in eval/results/. Nothing about adding a task can move a round-1
number; if it does, this script is wrong.

Design property #2 — TWO weight sets are supported explicitly, side by side, neither one silently
replacing the other:

  - `round1` — verbatim from docs/methodology.md §4 as originally published. `composite` /
    `terms` / `missing_terms` on every row are ALWAYS this weighting, unconditionally, so the
    Phase 6 gate (`build_gate`, below) and anything reading the legacy field names (e.g.
    `validate_correlation.py`) keep working byte-for-byte forever, regardless of `--weights`.
  - `round2` — tool_malformed 0.25 -> 0.10 (bimodal, not saturated, in round-1 data: a tight
    2.4-5.5% cluster where the ordinal differences are ~noise, alongside 8.7/10.5/17.9-19.3/
    27.8-32.5% outliers 2-10x worse that a small weight already punishes decisively), the freed
    0.15 split +0.10 B_recall (round-1's healthiest, least-saturated axis: 0.111-0.611) and +0.05
    C_edit (narrower spread: 0.803-0.909). Emitted on every row as `composite_round2_weights` /
    `terms_round2_weights` / `missing_terms_round2_weights`, ADDITIONAL to the round-1 fields,
    never overwriting them.

Both weight sets are validated to sum to 1.00 at import time (`_validate_weight_sets`) and raise
immediately if they don't -- a silently-unbalanced weighting would corrupt every composite below
it without any visible symptom.

The round-2-weighted composite is NOT the same quantity as the round-1 leaderboard composite --
see `ROUND2_COMPARABILITY_NOTE` below, repeated next to every place the number is rendered.

Design property #3 — COVERAGE IS DATA, NOT PROSE. A composite is only as complete as the task
set it was computed over, and mid-run that set is whatever happened to finish. Every row carries
`coverage` (tasks-with-units vs tasks-the-set-defines, overall and per suite) plus a
`composite_coverage` status string sitting directly next to the composite it qualifies.
`missing_terms` does NOT cover this: it is per-AXIS, so a config holding only round-1 tasks
still has *some* data on every axis and reports `missing_terms: []` while its composite was
computed over a third of the selected task set. A partial composite is useful during a run; a
partial composite that presents itself as complete is not. So it is labelled, never suppressed.

Design property #4 — THE SAME RULE FOR THE EXTERNAL LANE. `bcb__*.json` / `ifeval__*.json` each
carry one headline float measured over whatever slice that run selected: `--limit 10` of
BigCodeBench-Hard's 148 tasks, or 20 of IFEval's 541 prompts. Read as a bare number, a gate probe
and a full-set run are indistinguishable — the identical failure that Design property #3 fixed
for the composite. So every external value is emitted with the denominator it was actually
measured over, the full-set size, whether that size came from the artifact or from a fallback
constant, and a coverage string; a missing denominator degrades to UNKNOWN, never to an assumed
full set. IFEval additionally carries a truncation-contamination flag (see
`CONVENTIONS["external_coverage"]`): a value can be worse than partial, and nothing here
re-scores anything.

The new round-2 axes (bcb_hard_pass@1, ifeval_prompt_strict) are reported ALONGSIDE, UNWEIGHTED,
independent of either weight set. Folding them in waits for evidence of correlation (see
validate_correlation.py).

Every component term is emitted per config, not just the composite, so a disagreement with the
hand-written table is diagnosable rather than mysterious.
"""

