def aggregate(results: Path, which_round: str, primary_weights: str = "round2") -> dict:
    tasks = task_set(which_round)
    units = load_units(results, tasks)
    d_by_model, d_by_config = load_judged(results, tasks)
    bcb = load_external(results, EXTERNAL_AXES["bcb_hard_pass@1"])
    ifeval = load_external(results, EXTERNAL_AXES["ifeval_prompt_strict"])

    acc: dict[tuple[str, str], dict[str, list]] = defaultdict(lambda: defaultdict(list))
    tools: dict[tuple[str, str], list[int]] = defaultdict(lambda: [0, 0])
    n_units: dict[tuple[str, str], int] = defaultdict(int)
    suite_units: dict[tuple[str, str], dict[str, int]] = defaultdict(
        lambda: defaultdict(int)
    )
    tasks_seen: dict[tuple[str, str], set[str]] = defaultdict(set)

    for d in units:
        k = (d["model"], d["quant"])
        n_units[k] += 1
        suite = d.get("suite")
        suite_units[k][suite] += 1
        tasks_seen[k].add(d["task"])
        g = d.get("grade") or {}
        if suite == "A_coding":
            if g.get("pass_rate") is not None:
                acc[k]["A"].append(g["pass_rate"])
        elif suite == "C_edit":
            pt = g.get("pytest")
            if isinstance(pt, dict) and pt.get("pass_rate") is not None:
                acc[k]["C"].append(pt["pass_rate"])
            df = g.get("diff")
            if isinstance(df, dict) and df.get("surgical_score") is not None:
                acc[k]["C_surg"].append(df["surgical_score"])
        elif suite == "B_review":
            if g.get("recall") is not None:
                acc[k]["B"].append(g["recall"])
            if g.get("precision") is not None:
                acc[k]["B_prec"].append(g["precision"])

        tc = (d.get("driver") or {}).get("tool_calls")
        if isinstance(tc, dict):
            tools[k][0] += tc.get("total", 0) or 0
            tools[k][1] += tc.get("malformed", 0) or 0

    rows: list[dict] = []
    for k in sorted(n_units, key=lambda kk: (kk[0], kk[1])):
        model, quant = k
        a = _mean3(acc[k]["A"])
        c = _mean3(acc[k]["C"])
        b = _mean3(acc[k]["B"])
        total, malformed = tools[k]
        raw_malformed = (malformed / total) if total else None
        rounded = (
            round(100 * raw_malformed) / 100 if raw_malformed is not None else None
        )
        d_model = _mean3(d_by_model.get(model, []))
        d_cfg = _mean3(d_by_config.get(k, []))
        dec = probe_decode(results, model, quant)
        coverage = build_coverage(tasks, frozenset(tasks_seen[k]))

        # raw (unweighted) per-axis components -- identical inputs feed both weight sets
        raw_axes: dict[str, float | None] = {
            "a_coding": a,
            "tool_reliability": None if rounded is None else (1 - rounded),
            "c_edit": c,
            "b_recall": b,
            "d_text": None if d_model is None else d_model / D_TEXT_SCALE,
            "decode": None if dec is None else dec / DECODE_NORM_TPS,
        }

        def _weighted(
            weights: dict[str, float], axes: dict[str, float | None] = raw_axes
        ) -> tuple[dict[str, float | None], list[str], float | None]:
            terms_: dict[str, float | None] = {}
            for name, w in weights.items():
                v = axes[name]
                terms_[name] = None if v is None else w * v
            missing_ = [name for name, v in terms_.items() if v is None]
            composite_ = (
                None
                if missing_
                else round(100 * sum(v for v in terms_.values() if v is not None), 2)
            )
            return terms_, missing_, composite_

        terms, missing, composite = _weighted(WEIGHT_SETS["round1"])
        terms_r2, missing_r2, composite_r2 = _weighted(WEIGHT_SETS["round2"])

        # diagnostic variant: per-config D instead of model-pooled D (round-1 weights only --
        # this is a D-pooling diagnostic, not a weighting one)
        composite_cfg_d = None
        if not [m for m in missing if m != "d_text"] and d_cfg is not None:
            alt_axes = dict(raw_axes)
            alt_axes["d_text"] = d_cfg / D_TEXT_SCALE
            _, _, composite_cfg_d = _weighted(WEIGHT_SETS["round1"], axes=alt_axes)

        rows.append(
            {
                "model": model,
                "quant": quant,
                "is_leaderboard_config": LEADERBOARD_QUANT.get(model) == quant,
                "n_units": n_units[k],
                "units_by_suite": dict(sorted(suite_units[k].items())),
                # How much of the SELECTED task set this row actually rests on. n_units alone
                # cannot say: 30 units is a complete round-1 row and a 10-of-31 round-all one.
                "coverage": coverage,
                "a_coding": a,
                "tool_calls_total": total,
                "tool_calls_malformed": malformed,
                "tool_malformed_pct_raw": None
                if raw_malformed is None
                else round(100 * raw_malformed, 3),
                "tool_malformed_pct_rounded": None
                if rounded is None
                else round(100 * rounded),
                "c_edit": c,
                "c_surgical_score": _mean3(acc[k]["C_surg"]),
                "b_recall": b,
                "b_precision": _mean3(acc[k]["B_prec"]),
                "d_text_model_pooled": d_model,
                "d_text_config": d_cfg,
                "decode_tps": dec,
                # -- round-1 weights (docs/methodology.md §4). UNCHANGED semantics: this is the
                # field the Phase 6 gate and validate_correlation.py have always read.
                "terms": {
                    kk: (None if v is None else round(v, 6)) for kk, v in terms.items()
                },
                "missing_terms": missing,
                # Qualifies `composite` AND `composite_round2_weights` below -- both are
                # combinations of the same per-axis scores, so both rest on the same tasks.
                # Never a reason to null either number; see CONVENTIONS["coverage"].
                "composite_coverage": coverage_status_line(coverage),
                "composite": composite,
                "composite_weights_version": "round1",
                "composite_config_d": composite_cfg_d,
                # -- round-2 weights (docs/methodology.md §6.11). ADDITIONAL, never overwrites
                # the round-1 fields above. NOT comparable to `composite` -- see
                # ROUND2_COMPARABILITY_NOTE.
                "terms_round2_weights": {
                    kk: (None if v is None else round(v, 6))
                    for kk, v in terms_r2.items()
                },
                "missing_terms_round2_weights": missing_r2,
                "composite_round2_weights": composite_r2,
                # round-2 external axes: reported alongside, UNWEIGHTED, absent -> null. The
                # value stays a bare float for every existing reader; the `_coverage` string
                # next to it says what denominator that float rests on, the same way
                # `composite_coverage` sits next to `composite`. Full provenance (n_measured,
                # n_full_set, ts, source file, contamination) is in
                # `external_axes_unweighted` below.
                "bcb_hard_pass@1": external_value(bcb, k),
                "bcb_hard_pass@1_coverage": external_row_coverage(bcb, k),
                "ifeval_prompt_strict": external_value(ifeval, k),
                "ifeval_prompt_strict_coverage": external_row_coverage(ifeval, k),
            }
        )

    # The gate ALWAYS reproduces against round-1 weights -- that is the formula the published
    # leaderboard used; --weights never touches which weighting the gate checks.
    gate = build_gate(rows, which_round)

    return {
        "schema_version": SCHEMA_VERSION,
        "generated_ts": datetime.now(timezone.utc).isoformat(),
        "round": which_round,
        "task_set": sorted(tasks),
        "tasks_found_on_disk": sorted({d["task"] for d in units}),
        # legacy top-level fields -- always round1, unconditionally (see Design property #2)
        "formula": FORMULA,
        "weights": WEIGHTS,
        # explicit, both weight sets, named and versioned
        "formulas": FORMULAS,
        "weight_sets": WEIGHT_SETS,
        "primary_weights": primary_weights,
        "round2_reweight_reason": ROUND2_REWEIGHT_REASON,
        "round2_comparability_note": ROUND2_COMPARABILITY_NOTE,
        "decode_norm_tps": DECODE_NORM_TPS,
        "leaderboard_quant": LEADERBOARD_QUANT,
        "conventions": CONVENTIONS,
        "n_units_total": len(units),
        "configs": rows,
        # Per config these are OBJECTS, not bare floats: the float alone cannot distinguish a
        # 10-task BigCodeBench probe from the full 148-task Hard set. `value` is the number
        # that used to be here; everything beside it says what that number covers.
        "external_axes_unweighted": {
            "bcb_hard_pass@1": {f"{m}__{q}": e for (m, q), e in sorted(bcb.items())},
            "ifeval_prompt_strict": {
                f"{m}__{q}": e for (m, q), e in sorted(ifeval.items())
            },
            "note": CONVENTIONS["external_axes"],
            "coverage_note": CONVENTIONS["external_coverage"],
        },
        "gate": gate,
    }


def build_gate(rows: list[dict], which_round: str) -> dict:
    """Compare the computed headline composite against the hand-written leaderboard table."""
    if which_round != "1":
        return {
            "applicable": False,
            "reason": "The published leaderboard covers the round-1 task set only; "
            "the gate is defined for --round 1.",
        }
    per_model = []
    for model, published in LEADERBOARD_COMPOSITE.items():
        row = next(
            (r for r in rows if r["model"] == model and r["is_leaderboard_config"]),
            None,
        )
        computed = row["composite"] if row else None
        entry = {
            "model": model,
            "quant": row["quant"] if row else LEADERBOARD_QUANT.get(model),
            "published": published,
            "computed": computed,
            "computed_1dp": None if computed is None else round(computed, 1),
            "delta": None if computed is None else round(computed - published, 3),
            "agrees_1dp": None if computed is None else round(computed, 1) == published,
        }
        per_model.append(entry)

    agree = [e for e in per_model if e["agrees_1dp"]]
    deltas = [abs(e["delta"]) for e in per_model if e["delta"] is not None]

    # rank agreement (the thing that actually drives the write-up)
    pub_rank = sorted(LEADERBOARD_COMPOSITE, key=lambda m: -LEADERBOARD_COMPOSITE[m])
    scored = [e for e in per_model if e["computed"] is not None]
    comp_rank = [e["model"] for e in sorted(scored, key=lambda e: -e["computed"])]

    return {
        "applicable": True,
        "source": "docs/leaderboard.md + eval/results/LEADERBOARD.md (identical composites)",
        "weights_used": "round1",  # always -- this is what the published table was computed with
        "n_models": len(per_model),
        "n_agree_1dp": len(agree),
        "max_abs_delta": round(max(deltas), 3) if deltas else None,
        "verdict": (
            f"REPRODUCED: {len(agree)}/{len(per_model)} models agree to 1 decimal place "
            f"(max |delta| {max(deltas):.3f})"
            if deltas and len(agree) == len(per_model)
            else f"MISMATCH: {len(agree)}/{len(per_model)} models agree to 1 decimal place"
        ),
        "published_rank": pub_rank,
        "computed_rank": comp_rank,
        "rank_identical": pub_rank == comp_rank,
        "per_model": per_model,
    }


