def _f(v, nd=3, dash="—"):
    if v is None:
        return dash
    if isinstance(v, bool):
        return "yes" if v else "no"
    return f"{v:.{nd}f}" if isinstance(v, float) else str(v)


def render_md(agg: dict) -> str:
    L: list[str] = []
    L.append(f"# AGGREGATE — round {agg['round']}")
    L.append("")
    L.append(
        f"*Generated {agg['generated_ts']} by `eval/harness/aggregate.py`. "
        f"{agg['n_units_total']} units over {len(agg['tasks_found_on_disk'])} tasks found on disk "
        f"(task set defines {len(agg['task_set'])}).*"
    )
    L.append("")
    L.append("```")
    L.append(f"Overall (round1 weights, published) = {agg['formulas']['round1']}")
    L.append(f"Overall (round2 weights)            = {agg['formulas']['round2']}")
    L.append("```")
    L.append("")
    L.append(f"> **Non-comparability:** {agg['round2_comparability_note']}")
    L.append("")

    gate = agg["gate"]
    L.append("## Gate — does this reproduce the hand-written leaderboard?")
    L.append("")
    if not gate["applicable"]:
        L.append(f"Not applicable: {gate['reason']}")
    else:
        L.append(
            f"**{gate['verdict']}**  ·  rank order identical: **{gate['rank_identical']}**"
        )
        L.append("")
        L.append(
            "| Model | Quant | Published | Computed | Computed (1dp) | Δ | Agrees @1dp |"
        )
        L.append("|---|---|--:|--:|--:|--:|:--:|")
        for e in gate["per_model"]:
            delta = "—" if e["delta"] is None else f"{e['delta']:+.3f}"
            mark = "OK" if e["agrees_1dp"] else "MISMATCH"
            L.append(
                f"| `{e['model']}` | {e['quant']} | {_f(e['published'], 1)} | "
                f"{_f(e['computed'], 2)} | {_f(e['computed_1dp'], 1)} | {delta} | {mark} |"
            )
    L.append("")

    L.append("## Per-config components")
    L.append("")
    L.append(
        "| Config | LB | n | A | tools% (raw) | 1−tools | C | B | D/10 | decode | decode/137 "
        "| **Composite (R1 wts)** | **Composite (R2 wts)†** | comp (per-cfg D) | BCB-Hard | IFEval |"
    )
    L.append("|---|:--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|")

    def _sort_key(r):
        return (
            -(r["composite"] if r["composite"] is not None else -1e9),
            r["model"],
            r["quant"],
        )

    for r in sorted(agg["configs"], key=_sort_key):
        tr = r["tool_malformed_pct_rounded"]
        raw = r["tool_malformed_pct_raw"]
        tools_col = "—" if tr is None else f"{tr}% ({raw:.2f}%)"
        rel_col = "—" if tr is None else f"{1 - tr / 100:.2f}"
        d = r["d_text_model_pooled"]
        d_col = "—" if d is None else f"{d / D_TEXT_SCALE:.3f}"
        dec = r["decode_tps"]
        dec_norm_col = "—" if dec is None else f"{dec / DECODE_NORM_TPS:.3f}"
        star = "*" if r["is_leaderboard_config"] else ""
        L.append(
            f"| `{r['model']}` {r['quant']} | {star} | {r['n_units']} | {_f(r['a_coding'])} | "
            f"{tools_col} | {rel_col} | {_f(r['c_edit'])} | {_f(r['b_recall'])} | {d_col} | "
            f"{_f(dec, 1)} | {dec_norm_col} | **{_f(r['composite'], 2)}** | "
            f"**{_f(r['composite_round2_weights'], 2)}†** | "
            f"{_f(r['composite_config_d'], 2)} | {_f(r['bcb_hard_pass@1'])} | "
            f"{_f(r['ifeval_prompt_strict'])} |"
        )
    L.append("")
    L.append(
        "`*` = the config the published leaderboard uses for this model's headline composite. "
        "`†` = round-2 weights (docs/methodology.md §6.11) -- **not the same quantity as the "
        "round-1-weighted composite to its left**; see the caveat at the top of this document "
        "and the reweighting-impact table below before comparing the two columns as a ranking."
    )
    L.append("")

    L.append(
        "## Reweighting impact — round-1 vs round-2 weights, same underlying scores"
    )
    L.append("")
    L.append(
        "Isolates the weight change from any task-set change: both composites below are "
        "computed from the *same* per-axis scores (this is `--round "
        + agg["round"]
        + "`), "
        "differing only in which weights combine them. Restricted to each model's headline "
        "(published-leaderboard) config."
    )
    L.append("")
    headline = [
        r
        for r in agg["configs"]
        if r["is_leaderboard_config"]
        and r["composite"] is not None
        and r["composite_round2_weights"] is not None
    ]
    r1_rank = sorted(headline, key=lambda r: -r["composite"])
    r2_rank = sorted(headline, key=lambda r: -r["composite_round2_weights"])
    r1_pos = {r["model"]: i + 1 for i, r in enumerate(r1_rank)}
    r2_pos = {r["model"]: i + 1 for i, r in enumerate(r2_rank)}
    if headline:
        L.append(
            "| Rank (R1 wts) | Model | Quant | Composite (R1 wts) | Composite (R2 wts) "
            "| Rank (R2 wts) | ΔRank |"
        )
        L.append("|--:|---|---|--:|--:|--:|:--:|")
        for r in r1_rank:
            m = r["model"]
            d_rank = r1_pos[m] - r2_pos[m]
            arrow = (
                "→ 0"
                if d_rank == 0
                else (f"↑ {d_rank}" if d_rank > 0 else f"↓ {-d_rank}")
            )
            L.append(
                f"| {r1_pos[m]} | `{m}` | {r['quant']} | {_f(r['composite'], 2)} | "
                f"{_f(r['composite_round2_weights'], 2)} | {r2_pos[m]} | {arrow} |"
            )
        L.append("")
        ranking_changed = [r["model"] for r in r1_rank] != [r["model"] for r in r2_rank]
        L.append(
            f"**Reweighting alone {'DOES' if ranking_changed else 'does NOT'} reorder the "
            f"fleet.**"
        )
    else:
        L.append("No headline configs have both composites computable.")
    L.append("")
    L.append(f"> **Why the reweight:** {agg['round2_reweight_reason']}")
    L.append("")

    incomplete = [r for r in agg["configs"] if r["missing_terms"]]
    if incomplete:
        L.append("### Configs with an incomputable composite")
        L.append("")
        for r in incomplete:
            L.append(
                f"- `{r['model']}__{r['quant']}`: missing {', '.join(r['missing_terms'])}"
            )
        L.append("")

    L.append("## Round-2 axes (reported alongside, UNWEIGHTED)")
    L.append("")
    ex = agg["external_axes_unweighted"]
    if not ex["bcb_hard_pass@1"] and not ex["ifeval_prompt_strict"]:
        L.append(
            "No `bcb__*.json` / `ifeval__*.json` result files on disk yet — both axes null."
        )
    else:
        L.append("| Config | bcb_hard_pass@1 | ifeval_prompt_strict |")
        L.append("|---|--:|--:|")
        for key in sorted(set(ex["bcb_hard_pass@1"]) | set(ex["ifeval_prompt_strict"])):
            L.append(
                f"| `{key}` | {_f(ex['bcb_hard_pass@1'].get(key))} | "
                f"{_f(ex['ifeval_prompt_strict'].get(key))} |"
            )
    L.append("")
    L.append(f"> {ex['note']}")
    L.append("")

    L.append(
        "## Term conventions (what each symbol in the formula actually means here)"
    )
    L.append("")
    for k, v in agg["conventions"].items():
        L.append(f"- **`{k}`** — {v}")
    L.append("")
    return "\n".join(L)


