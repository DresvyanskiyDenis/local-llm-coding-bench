def _f(v, nd=3, dash="—"):
    if v is None:
        return dash
    if isinstance(v, bool):
        return "yes" if v else "no"
    return f"{v:.{nd}f}" if isinstance(v, float) else str(v)


def render_md(agg: dict) -> str:
    L: list[str] = []
    L.append(f"# AGGREGATE — round {agg['round']}")
    L.append("")
    L.append(
        f"*Generated {agg['generated_ts']} by `eval/harness/aggregate.py`. "
        f"{agg['n_units_total']} units over {len(agg['tasks_found_on_disk'])} tasks found on disk "
        f"(task set defines {len(agg['task_set'])}).*"
    )
    L.append("")
    L.append("```")
    L.append(f"Overall = {agg['formula']}")
    L.append("```")
    L.append("")

    gate = agg["gate"]
    L.append("## Gate — does this reproduce the hand-written leaderboard?")
    L.append("")
    if not gate["applicable"]:
        L.append(f"Not applicable: {gate['reason']}")
    else:
        L.append(
            f"**{gate['verdict']}**  ·  rank order identical: **{gate['rank_identical']}**"
        )
        L.append("")
        L.append(
            "| Model | Quant | Published | Computed | Computed (1dp) | Δ | Agrees @1dp |"
        )
        L.append("|---|---|--:|--:|--:|--:|:--:|")
        for e in gate["per_model"]:
            delta = "—" if e["delta"] is None else f"{e['delta']:+.3f}"
            mark = "OK" if e["agrees_1dp"] else "MISMATCH"
            L.append(
                f"| `{e['model']}` | {e['quant']} | {_f(e['published'], 1)} | "
                f"{_f(e['computed'], 2)} | {_f(e['computed_1dp'], 1)} | {delta} | {mark} |"
            )
    L.append("")

    L.append("## Per-config components")
    L.append("")
    L.append(
        "| Config | LB | n | A | tools% (raw) | 1−tools | C | B | D/10 | decode | decode/137 "
        "| **Composite** | comp (per-cfg D) | BCB-Hard | IFEval |"
    )
    L.append("|---|:--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|")

    def _sort_key(r):
        return (
            -(r["composite"] if r["composite"] is not None else -1e9),
            r["model"],
            r["quant"],
        )

    for r in sorted(agg["configs"], key=_sort_key):
        tr = r["tool_malformed_pct_rounded"]
        raw = r["tool_malformed_pct_raw"]
        tools_col = "—" if tr is None else f"{tr}% ({raw:.2f}%)"
        rel_col = "—" if tr is None else f"{1 - tr / 100:.2f}"
        d = r["d_text_model_pooled"]
        d_col = "—" if d is None else f"{d / D_TEXT_SCALE:.3f}"
        dec = r["decode_tps"]
        dec_norm_col = "—" if dec is None else f"{dec / DECODE_NORM_TPS:.3f}"
        star = "*" if r["is_leaderboard_config"] else ""
        L.append(
            f"| `{r['model']}` {r['quant']} | {star} | {r['n_units']} | {_f(r['a_coding'])} | "
            f"{tools_col} | {rel_col} | {_f(r['c_edit'])} | {_f(r['b_recall'])} | {d_col} | "
            f"{_f(dec, 1)} | {dec_norm_col} | **{_f(r['composite'], 2)}** | "
            f"{_f(r['composite_config_d'], 2)} | {_f(r['bcb_hard_pass@1'])} | "
            f"{_f(r['ifeval_prompt_strict'])} |"
        )
    L.append("")
    L.append(
        "`*` = the config the published leaderboard uses for this model's headline composite."
    )
    L.append("")

    incomplete = [r for r in agg["configs"] if r["missing_terms"]]
    if incomplete:
        L.append("### Configs with an incomputable composite")
        L.append("")
        for r in incomplete:
            L.append(
                f"- `{r['model']}__{r['quant']}`: missing {', '.join(r['missing_terms'])}"
            )
        L.append("")

    L.append("## Round-2 axes (reported alongside, UNWEIGHTED)")
    L.append("")
    ex = agg["external_axes_unweighted"]
    if not ex["bcb_hard_pass@1"] and not ex["ifeval_prompt_strict"]:
        L.append(
            "No `bcb__*.json` / `ifeval__*.json` result files on disk yet — both axes null."
        )
    else:
        L.append("| Config | bcb_hard_pass@1 | ifeval_prompt_strict |")
        L.append("|---|--:|--:|")
        for key in sorted(set(ex["bcb_hard_pass@1"]) | set(ex["ifeval_prompt_strict"])):
            L.append(
                f"| `{key}` | {_f(ex['bcb_hard_pass@1'].get(key))} | "
                f"{_f(ex['ifeval_prompt_strict'].get(key))} |"
            )
    L.append("")
    L.append(f"> {ex['note']}")
    L.append("")

    L.append(
        "## Term conventions (what each symbol in the formula actually means here)"
    )
    L.append("")
    for k, v in agg["conventions"].items():
        L.append(f"- **`{k}`** — {v}")
    L.append("")
    return "\n".join(L)


# --------------------------------------------------------------------------------------------
def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--round",
        choices=["1", "2", "all"],
        default="1",
        help="which task set to score",
    )
    ap.add_argument("--results", type=Path, default=RESULTS, help="results directory")
    ap.add_argument(
        "--json",
        type=Path,
        default=None,
        help="output JSON (default results/AGGREGATE.json)",
    )
    ap.add_argument(
        "--out", type=Path, default=None, help="also write the markdown table here"
    )
    ap.add_argument(
        "--quiet", action="store_true", help="do not print the markdown table"
    )
    ap.add_argument(
        "--fail-on-gate",
        action="store_true",
        help="exit 1 if the round-1 gate does not reproduce the published leaderboard",
    )
    a = ap.parse_args()

    if not a.results.is_dir():
        print(f"error: results dir not found: {a.results}", file=sys.stderr)
        return 2

    agg = aggregate(a.results, a.round)

    suffix = "" if a.round == "1" else f"__round{a.round}"
    out_json = a.json or (a.results / f"AGGREGATE{suffix}.json")
    out_json.parent.mkdir(parents=True, exist_ok=True)
    tmp = out_json.with_suffix(out_json.suffix + ".tmp")
    tmp.write_text(json.dumps(agg, indent=2) + "\n")
    tmp.replace(out_json)

    md = render_md(agg)
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(md)
    if not a.quiet:
        print(md)

    print(f"\nwrote {out_json}" + (f" and {a.out}" if a.out else ""), file=sys.stderr)

    gate = agg["gate"]
    if gate["applicable"]:
        print(f"gate: {gate['verdict']}", file=sys.stderr)
        if a.fail_on_gate and gate["n_agree_1dp"] != gate["n_models"]:
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
